package com.example.demo.entity;

import jakarta.persistence.*;
@Entity                       // This class becomes a database table
@Table(name = "student")
public class StudentEntity {

    @Id                                                   // Primary key
    @GeneratedValue(strategy = GenerationType.IDENTITY)   // Auto-increment
    private int id;
    
    private String name;      // becomes a column
    private String course;    // becomes a column
    
    // default constructor
    public StudentEntity(){} 
    public StudentEntity(String name, String course){ 
        this.name = name;
        this.course = course;
    }
    // why there's no id in the constructor?
    // - Because the id is automatically generated by the database.

    // Setters
    public void setName(String name) { this.name = name; }
    public void setCourse(String course) { this.course = course; }

    // Getters 
    public int getId() { return id; } 
    public String getName() { return name; }
    public String getCourse() { return course; }
    
    //why there's no setters in in?
    // Because the ID is automatically generated and should not normally be manually modified.
}